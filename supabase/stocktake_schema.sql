create table if not exists public.it_stocktake_sessions (
  id            uuid primary key default gen_random_uuid(),
  seq           bigint generated by default as identity,

  location      text not null,
  status        text not null default '진행중' check (status in ('진행중', '완료')),
  started_by    text not null default '',
  results       jsonb not null default '[]'::jsonb,

  started_at    timestamptz not null default now(),
  completed_at  timestamptz,

  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists it_stocktake_sessions_location_idx on public.it_stocktake_sessions (location);

drop trigger if exists it_stocktake_sessions_set_updated_at on public.it_stocktake_sessions;
create trigger it_stocktake_sessions_set_updated_at
  before update on public.it_stocktake_sessions
  for each row execute function public.set_updated_at();

-- 다른 대장들과 동일한 보안 모델: RLS 켜고 정책은 만들지 않음 → service_role 서버 코드만 접근
alter table public.it_stocktake_sessions enable row level security;
