-- jsonb 배열로 통째로 담습니다(건별 자식 테이블 대신 — 조회/검색이 필요 없고 세션 단위로만
-- 읽고 쓰는 용도라 더 단순함):
--   [{ assetId, category, model, brand, status, scannedAt, note }]
--   status: '미확인' | '확인됨' | '목록외발견'
